import createImageUrlBuilder from '@sanity/image-url'
import { dataset, projectId } from './sanity'

const builder = createImageUrlBuilder({ projectId, dataset })

/**
 * Builds a Sanity CDN URL. Hotspot and crop data set in the Studio are
 * respected automatically when `.fit('crop')` is used.
 *
 * The package exposes no public subpath for `SanityImageSource`, so the
 * argument is typed with the local `SanityImage` shape the queries return.
 */
export const urlFor = (source: SanityImage) => builder.image(source)

export interface SanityImage {
  asset?: {
    _id?: string
    url?: string
    metadata?: {
      /** Base64 blur placeholder, ~1kB, generated by Sanity on upload. */
      lqip?: string
      dimensions?: { width: number; height: number; aspectRatio: number }
    }
  }
  alt?: string
  hotspot?: { x: number; y: number }
  crop?: { top: number; bottom: number; left: number; right: number }
}
